//eint.c

#include <LPC21xx.h>
#include "types.h"
#include "eint.h"


/*==========================================================
                    EINT1 VIC CHANNEL
  ==========================================================*/

/*
   LPC2148 VIC:

       EINT0 -> Channel 14
       EINT1 -> Channel 15

   Therefore EINT1 uses channel 15.
*/

#define EINT1_CH    15


/*==========================================================
                    EDIT REQUEST FLAG
  ==========================================================*/

volatile u8 edit_request = 0;


/*==========================================================
                    INITIALIZE EINT1
  ==========================================================*/

void Init_EINT(void)
{
    /*------------------------------------------------------
                    P0.3 -> EINT1
      ------------------------------------------------------*/

    /*
       P0.3 PINSEL0 bits = 7:6

       Function:
           00 -> GPIO
           01 -> EINT1
    */

    PINSEL0 &= ~(3 << 6);
    PINSEL0 |=  (3 << 6);


    /*------------------------------------------------------
                    CLEAR PENDING EINT1
      ------------------------------------------------------*/

    EXTINT = (1 << 1);


    /*------------------------------------------------------
                    EDGE TRIGGERED
      ------------------------------------------------------*/

    EXTMODE |= (1 << 1);


    /*------------------------------------------------------
                    FALLING EDGE
      ------------------------------------------------------*/

    EXTPOLAR &= ~(1 << 1);


    /*------------------------------------------------------
                    EINT1 AS IRQ
      ------------------------------------------------------*/

    VICIntSelect &= ~(1 << EINT1_CH);


    /*------------------------------------------------------
                    ISR ADDRESS
      ------------------------------------------------------*/

    VICVectAddr0 = (unsigned)eint1_isr;


    /*------------------------------------------------------
                    VECTOR CONTROL
      ------------------------------------------------------*/

    VICVectCntl0 = (1 << 5) | EINT1_CH;


    /*------------------------------------------------------
                    ENABLE EINT1
      ------------------------------------------------------*/

    VICIntEnable = (1 << EINT1_CH);
}


/*==========================================================
                    EINT1 ISR
  ==========================================================*/

void eint1_isr(void) __irq
{
    /*
       Do not perform LCD/keypad/EEPROM operations
       inside the ISR.

       Only set the flag.
    */

    edit_request = 1;


    /*------------------------------------------------------
                    CLEAR EINT1 INTERRUPT
      ------------------------------------------------------*/

    EXTINT = (1 << 1);


    /*------------------------------------------------------
                    END OF INTERRUPT
      ------------------------------------------------------*/

    VICVectAddr = 0;
}
